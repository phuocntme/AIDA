// Writes ABIs from Hardhat artifacts into packages/sdk/src/abi.ts
import { readFileSync, writeFileSync } from "node:fs";
const names = ["IdentityRegistry", "ReputationRegistry", "ValidationRegistry"];
let out = "// Generated by packages/contracts/scripts/export-abi.mjs — do not edit\n";
for (const n of names) {
  const a = JSON.parse(readFileSync(new URL(`../artifacts/contracts/${n}.sol/${n}.json`, import.meta.url)));
  const id = n[0].toLowerCase() + n.slice(1, n.indexOf("Registry")) + "Abi";
  out += `export const ${id} = ${JSON.stringify(a.abi, null, 2)} as const;\n`;
}
writeFileSync(new URL("../../sdk/src/abi.ts", import.meta.url), out);
console.log("wrote sdk/src/abi.ts");
