// Writes ABIs from Hardhat artifacts into packages/sdk/src/abi.ts
import { readFileSync, writeFileSync } from "node:fs";
const sources = [
  ["identityAbi", "local/LocalIdentityRegistry.sol/LocalIdentityRegistry"], // same surface as the canonical ERC-8004 registry
  ["reviewsAbi", "PaidReviews.sol/PaidReviews"],
  ["validationAbi", "ValidationRegistry.sol/ValidationRegistry"],
  ["agentPolicyAbi", "AgentPolicy.sol/AgentPolicy"],
];
let out = "// Generated by packages/contracts/scripts/export-abi.mjs — do not edit\n";
for (const [id, path] of sources) {
  const a = JSON.parse(readFileSync(new URL(`../artifacts/contracts/${path}.json`, import.meta.url)));
  out += `export const ${id} = ${JSON.stringify(a.abi)} as const;\n`;
}
writeFileSync(new URL("../../sdk/src/abi.ts", import.meta.url), out);
console.log("wrote sdk/src/abi.ts");
